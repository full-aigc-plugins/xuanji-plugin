def draw_sign(seed: int | None, question: str | None) -> dict:
    rng = random.Random(seed)
    index, level, title, verse, hint = rng.choice(SIGNS)
    return {
        "question": question,
        "seed": seed,
        "sign": {"index": index, "level": level, "title": title, "verse": verse, "hint": hint},
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="月老求签（可播种复现）")
    parser.add_argument("--question", help="所问姻缘之事（仅记录）")
    parser.add_argument("--seed", type=int, help="随机种子（复现用）")
    args = parser.parse_args()
    print(json.dumps(draw_sign(args.seed, args.question), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
